def is_armstrong_gemini(number: int) -> bool:
    """
    Checks if a number is an Armstrong (Narcissistic) number.
    Generated by Google Gemini in Colab using mathematical decomposition.
    """
    if not isinstance(number, int) or number < 0:
        return False
        
    num_str = str(number)
    num_digits = len(num_str)
    
    # Calculate sum of digits raised to the power of number of digits
    total_sum = 0
    for char_digit in num_str:
        total_sum += int(char_digit) ** num_digits
        
